"""Frozen baseline of historical ``dod_evidence`` items that are sole ``file_exists``.

omnibase_core 0.47.26 (``ModelContractDodItem.reject_sole_file_exists_check``,
omnibase_core#1804) refuses a ``dod_evidence`` item whose only check type is
``file_exists``. The 56 contracts that declared such items were merged before
that rule existed and are append-only history: editing them would rewrite what
their tickets were closed against. ``validate-yaml`` therefore hands core a
copy of exactly these items with ``checks`` withheld (an item with no checks is
valid in core) and every other field still validated.

THIS IS A BURN-DOWN BASELINE, NOT AN ALLOWLIST FOR NEW WORK. An item that is
not in this set and is sole ``file_exists`` still fails ``validate-yaml`` with
``DOD_EVIDENCE_FILE_EXISTS_SOLE_CHECK``. Entries are ``<ticket>:<item id>``.
The set may only shrink: ``tests/unit/scripts/test_legacy_sole_file_exists.py``
pins its size ceiling and that every entry still names a real sole
``file_exists`` item in the corpus, so a migrated contract must drop its entry
in the same change.
"""

